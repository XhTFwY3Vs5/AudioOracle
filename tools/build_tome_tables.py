#!/usr/bin/env python3
"""
build_tome_tables.py — compact the curated Tome of Adventure Design tables from
tome_parser's per-table JSON exports and embed them into AudioOracle.html.

The scene generator is a single self-contained file; fetching sibling JSON from
file:// is blocked by browser CORS rules, so the curated subset is embedded as a
JS constant between the BEGIN/END markers in AudioOracle.html.

Usage:
    python3 tools/build_tome_tables.py --data ../tome_parser/data
    python3 tools/build_tome_tables.py --data ../tome_parser/data --check

The script is deterministic: rerunning it against the same inputs produces the
same embedded block.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# AudioOracle.html markers. Everything between them is replaced.
BEGIN_MARKER = "    // BEGIN TOME TABLES — generated by tools/build_tome_tables.py; do not edit by hand."
END_MARKER = "    // END TOME TABLES"

# Curated subset. Only tables that directly feed a scene seed are included.
# id -> (source file stem, source column keys)
TABLES: dict[str, tuple[str, list[str]]] = {
    # Frame / place
    "4-1": ("4_1", ["adventure_type"]),
    "1-1a": ("1_1a", ["structure_s_description", "structure", "feature_first_word", "feature_second_word"]),
    "1-1b": ("1_1b", [
        "structure_s_description",
        "structure",
        "feature_first_word",
        "feature_second_word_put_preference_on_the_singular",
    ]),
    "1-2": ("1_2", ["location_contents_word_one", "location_contents_word_two"]),
    # People, missions, hooks, plans
    "1-3": ("1_3", ["type_of_mission"]),
    "1-4": ("1_4", ["mission", "individual_subject_of_mission"]),
    "1-5": ("1_5", ["mission", "item_subject_of_mission"]),
    "1-6": ("1_6", ["mission", "location_subject_of_mission"]),
    "1-7": ("1_7", ["mission", "event_subject_of_mission"]),
    "1-8": ("1_8", ["patron_or_target"]),
    "1-9": ("1_9", ["motivation", "object_or_obstacle"]),
    "1-10": ("1_10", [
        "what_might_motivate_players_to_choose_this_adventure",
        "how_characters_learn_about_the_opportunity",
    ]),
    "1-11": ("1_11", ["type_of_villainous_plan"]),
    # Complications and texture
    "2-1": ("2_1", ["monster_category"]),
    "3-6": ("3_6", [
        "why_the_adventure_location_became_dangerous_factor_number_one",
        "why_the_adventure_location_became_dangerous_factor_number_two",
        "when_i_f_you_aren_t_looking_for_a_specific_timeframe",
    ]),
    "3-53a": ("3_53a", ["part_one", "part_two"]),
    "3-53b": ("3_53b", ["part_one", "part_two"]),
    "3-66": ("3_66", ["unusual_lighting"]),
    "3-71": ("3_71", ["sound"]),
    "3-78": ("3_78", ["what_comes_next"]),
    "3-82": ("3_82", ["type_of_hint", "problems_with_hint"]),
    "3-96": ("3_96", ["warnings"]),
    "3-144": ("3_144", ["dungeon_dressing_item"]),
    "3-145": ("3_145", ["unusual_corpse"]),
    "3-147": ("3_147", ["weird_dungeon_dressing_item"]),
    "3-151": ("3_151", ["small_item"]),
    "4-24": ("4_24", ["city_districts"]),
    "4-26": ("4_26", ["type_of_business"]),
    "4-29": ("4_29", ["news_or_rumor"]),
    "4-30": ("4_30", ["type_of_faction_war"]),
}

MAX_CHARS = 220

# Rows that are not useful as seeds (e.g. "None." in the warnings table).
SKIP_ROWS = {
    "3-96": re.compile(r"^None\."),
}

_TABLE_REF = re.compile(
    r"\s*\((?:see\s+)?Tables?\s+\d+\s*[-\u2013]\s*\d+[^)]*\)",
    re.IGNORECASE,
)
_PAGE_REF = re.compile(r"\s*\(\s*(?:page|p\.)\s*\d+[^)]*\)", re.IGNORECASE)
_ROLL_PAREN = re.compile(r"\s*\(roll[^)]*\)", re.IGNORECASE)
_ROLL_ON_TABLE = re.compile(r"^Roll on Tables?\s+\d+\s*[-\u2013]\s*\d+.*$", re.IGNORECASE)
_SEE_SENTENCE = re.compile(
    r"\s*See Tables?\s+\d+\s*[-\u2013]\s*\d+[^.]*\.",
    re.IGNORECASE,
)
_SEE_ABOVE = re.compile(r"\s*\(see tables? above[^)]*\)", re.IGNORECASE)


def clean(text: str) -> str:
    """Normalise a table cell for use as a short LLM seed."""
    text = str(text).replace("\u00ad", "")
    text = re.sub(r"\s+", " ", text).strip()
    text = text.replace("I f you", "If you")
    text = _TABLE_REF.sub("", text)
    text = _PAGE_REF.sub("", text)
    text = _SEE_SENTENCE.sub("", text)
    text = _SEE_ABOVE.sub("", text)
    if _ROLL_ON_TABLE.match(text):
        text = "a patron or target"
    text = _ROLL_PAREN.sub("", text)
    text = text.strip(" ;,")
    if len(text) > MAX_CHARS:
        cut = text[:MAX_CHARS].rsplit(" ", 1)[0].rstrip(" ,;:")
        text = cut + "\u2026"
    return text


def load_table(data_dir: Path, table_id: str, source: str, columns: list[str]) -> dict:
    path = data_dir / f"{source}.json"
    if not path.exists():
        raise FileNotFoundError(f"missing source table for {table_id}: {path}")
    raw = json.loads(path.read_text(encoding="utf-8"))

    rows: list[list] = []
    for row in raw["rows"]:
        roll = row.get("roll")
        if not isinstance(roll, list) or len(roll) != 2:
            raise ValueError(f"{table_id}: malformed roll in {path.name}: {roll!r}")
        lo, hi = int(roll[0]), int(roll[1])
        values = []
        for key in columns:
            if key not in row:
                raise KeyError(f"{table_id}: missing column {key!r} in {path.name}")
            values.append(clean(row[key]))
        skip = SKIP_ROWS.get(table_id)
        if skip and any(skip.search(v) for v in values):
            continue
        if table_id == "1-8":
            values = [v + " someone" if v.endswith(" of") else v for v in values]
        rows.append([lo, hi, *values])

    rows.sort(key=lambda r: (r[0], r[1]))
    die = int(raw.get("die", "d100").lstrip("dD"))
    covered = {n for lo, hi, *_ in rows for n in range(lo, hi + 1)}
    missing = sorted(set(range(1, die + 1)) - covered)
    if missing and table_id not in SKIP_ROWS:
        print(
            f"warning: {table_id} ({raw['title']}) does not cover rolls "
            f"{missing[0]}-{missing[-1]} ({len(missing)} values)",
            file=sys.stderr,
        )
    if rows[-1][1] > die:
        raise ValueError(f"{table_id}: row range exceeds {die}")

    return {
        "die": die,
        "rows": rows,
    }


def build_registry(data_dir: Path) -> dict:
    return {
        table_id: load_table(data_dir, table_id, source, columns)
        for table_id, (source, columns) in TABLES.items()
    }


def render_block(registry: dict) -> str:
    payload = json.dumps(registry, ensure_ascii=False, separators=(",", ":"))
    return (
        f"{BEGIN_MARKER}\n"
        "    // Curated Tome of Adventure Design tables, compacted for scene seeds.\n"
        "    // Source: Tome of Adventure Design (Matt Finch, Frog God Games).\n"
        "    // Each table: { die, rows: [[rollLow, rollHigh, ...cells], ...] }.\n"
        f"    const TOME_TABLES = {payload};\n"
        f"{END_MARKER}"
    )


def replace_block(html: str, block: str) -> str:
    start = html.find(BEGIN_MARKER)
    end = html.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise SystemExit(
            "Could not find the TOME TABLES markers in AudioOracle.html. "
            "Add the BEGIN/END marker comments first."
        )
    return html[:start] + block + html[end + len(END_MARKER):]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data",
        type=Path,
        default=Path(__file__).resolve().parents[2] / "tome_parser" / "data",
        help="directory containing tome_parser's per-table JSON files",
    )
    parser.add_argument(
        "--html",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "AudioOracle.html",
        help="AudioOracle.html to update",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="report the embedded block size without writing the file",
    )
    args = parser.parse_args()

    if not args.data.is_dir():
        print(f"error: data directory not found: {args.data}", file=sys.stderr)
        return 1

    registry = build_registry(args.data)
    block = render_block(registry)
    html = args.html.read_text(encoding="utf-8")
    updated = replace_block(html, block)

    if args.check:
        print(f"tables: {len(registry)}")
        print(f"rows:   {sum(len(t['rows']) for t in registry.values())}")
        print(f"block:  {len(block.encode('utf-8')) / 1024:.1f} KiB")
        print(f"html:   {len(html.encode('utf-8')) / 1024:.1f} KiB -> "
              f"{len(updated.encode('utf-8')) / 1024:.1f} KiB")
        return 0

    args.html.write_text(updated, encoding="utf-8")
    print(
        f"embedded {len(registry)} tables / "
        f"{sum(len(t['rows']) for t in registry.values())} rows "
        f"({len(block.encode('utf-8')) / 1024:.1f} KiB) into {args.html}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
